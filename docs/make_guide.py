def P(t, s="p"):
    return Paragraph(t, ST[s])


def bullets(items):
    return [Paragraph(i, ST["b"], bulletText="•") for i in items]


def box(text, color=LIGHT, title=None):
    content = []
    if title:
        content.append(Paragraph(f"<b>{title}</b>", ST["box"]))
    content.append(Paragraph(text, ST["box"]))
    t = Table([[content]], colWidths=[16.5 * cm])
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), color), ("BOX", (0, 0), (-1, -1), 0.5, colors.lightgrey),
                           ("LEFTPADDING", (0, 0), (-1, -1), 8), ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                           ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
    return KeepTogether([t, Spacer(1, 8)])


def table(rows, widths, zebra=True):
    data = [[Paragraph(str(c), ST["cellb"]) for c in rows[0]]]
    data += [[Paragraph(str(c), ST["cell"]) for c in r] for r in rows[1:]]
    t = Table(data, colWidths=[w * cm for w in widths], repeatRows=1)
    style = [("BACKGROUND", (0, 0), (-1, 0), BLUE), ("GRID", (0, 0), (-1, -1), 0.4, colors.lightgrey),
             ("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 4),
             ("RIGHTPADDING", (0, 0), (-1, -1), 4)]
    if zebra:
        for i in range(2, len(data), 2):
            style.append(("BACKGROUND", (0, i), (-1, i), GREY))
    t.setStyle(TableStyle(style))
    return KeepTogether([t, Spacer(1, 8)])


